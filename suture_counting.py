def parse_points(points_text):
    points = []

    for item in points_text.split(";"):
        item = item.strip()

        if not item:
            continue

        x_text, y_text = item.split(",")
        points.append([
            float(x_text),
            float(y_text)
        ])

    return np.asarray(points, dtype=np.float32)


def polyline_to_polygon(
    points,
    image_width,
    image_height,
    thickness=14
):
    if len(points) < 2:
        return None

    mask = np.zeros(
        (image_height, image_width),
        dtype=np.uint8
    )

    points_int = np.rint(points).astype(np.int32)

    points_int[:, 0] = np.clip(
        points_int[:, 0],
        0,
        image_width - 1
    )

    points_int[:, 1] = np.clip(
        points_int[:, 1],
        0,
        image_height - 1
    )

    cv2.polylines(
        mask,
        [points_int.reshape(-1, 1, 2)],
        isClosed=False,
        color=255,
        thickness=thickness,
        lineType=cv2.LINE_8
    )

    radius = max(1, thickness // 2)

    cv2.circle(
        mask,
        tuple(points_int[0]),
        radius,
        255,
        -1
    )

    cv2.circle(
        mask,
        tuple(points_int[-1]),
        radius,
        255,
        -1
    )

    contours, _ = cv2.findContours(
        mask,
        cv2.RETR_EXTERNAL,
        cv2.CHAIN_APPROX_NONE
    )

    if not contours:
        return None

    contour = max(
        contours,
        key=cv2.contourArea
    )

    contour = cv2.approxPolyDP(
        contour,
        epsilon=1.5,
        closed=True
    )

    contour = contour.reshape(-1, 2)

    if len(contour) < 3:
        return None

    polygon = []

    for x, y in contour:
        polygon.extend([
            float(x) / image_width,
            float(y) / image_height
        ])

    return polygon


